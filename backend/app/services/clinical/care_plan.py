"""Care-plan draft generation for OmniMed.

Flow: patient state + clinical brief -> evidence lookup (Qdrant) -> LLM draft
-> code-side validation -> clinician review. The output is always a draft.
Nothing here diagnoses, prescribes, orders, or approves.

The streaming endpoint (care_plan_stream.py) reuses the same steps, so the
streamed and non-streamed paths behave identically.

Small local models ignore prompt rules, so the rules that matter most are
enforced in code after generation (see `_polish`).
"""

